/**
 * Regenerates src/parsers/evtx/maps.ts from Eric Zimmerman's EvtxECmd map files.
 *
 *   git clone --depth 1 https://github.com/EricZimmerman/evtx.git
 *   node scripts/gen-evtx-maps.mjs path/to/evtx/evtx/Maps
 *
 * The .map files are YAML deserialised by EvtxECmd into EventLogMap (see
 * .refs/EventLogMap.cs), so we parse them with a real YAML parser rather than
 * by hand: the templates contain backslash escapes that only a conforming
 * parser gets right.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { parse } from 'yaml';

const dir = process.argv[2];
if (!dir) {
  console.error('usage: node scripts/gen-evtx-maps.mjs <EvtxECmd Maps dir>');
  process.exit(1);
}

const files = readdirSync(dir).filter((f) => f.toLowerCase().endsWith('.map')).sort();
const maps = [];

for (const f of files) {
  // The failsafe schema keeps every scalar a string, which is what EvtxECmd
  // gets from YamlDotNet. It matters: a lookup table can key the same value
  // both as 0xC000005E and as 3221225566, which the core schema would collapse
  // into one duplicate integer key.
  const y = parse(readFileSync(join(dir, f), 'utf8'), { schema: 'failsafe' });

  const properties = (y.Maps ?? []).map((m) => ({
    property: m.Property ?? '',
    template: m.PropertyValue ?? '',
    values: (m.Values ?? []).map((v) => {
      const out = { name: v.Name ?? '', path: v.Value ?? '' };
      if (v.Refine) out.refine = v.Refine;
      return out;
    }),
  }));

  const map = {
    eventId: Number(y.EventId),
    channel: String(y.Channel),
    provider: String(y.Provider),
    description: y.Description ?? '',
    properties,
  };

  if (y.Lookups) {
    map.lookups = y.Lookups.map((l) => ({
      name: l.Name ?? '',
      // EvtxECmd calls this Default; renamed here because `default` is reserved.
      defaultVal: l.Default == null ? '' : String(l.Default),
      values: Object.fromEntries(
        Object.entries(l.Values ?? {}).map(([k, v]) => [String(k), String(v)]),
      ),
    }));
  }

  maps.push(map);
}

const body = maps.map((m) => `  ${JSON.stringify(m)},`).join('\n');

writeFileSync(
  new URL('../src/parsers/evtx/maps.ts', import.meta.url),
  `// Auto-generated by scripts/gen-evtx-maps.mjs from Eric Zimmerman's EvtxECmd
// maps (https://github.com/EricZimmerman/evtx, evtx/Maps/*.map). ${maps.length} maps.
// Do not edit by hand.
export interface EventMapValue {
  name: string;
  /** XPath into the event XML, as written in the .map file. */
  path: string;
  /** Optional regex applied to the selected value. */
  refine?: string;
}

export interface EventMapProperty {
  /** UserName, RemoteHost, ExecutableInfo or PayloadData1-6. */
  property: string;
  /** PropertyValue: a template with %name% placeholders. */
  template: string;
  values: EventMapValue[];
}

export interface EventMapLookup {
  name: string;
  defaultVal: string;
  values: Record<string, string>;
}

export interface EventMap {
  eventId: number;
  channel: string;
  provider: string;
  description: string;
  properties: EventMapProperty[];
  lookups?: EventMapLookup[];
}

export const EVENT_MAPS: EventMap[] = [
${body}
];

const BY_KEY = new Map<string, EventMap>(
  EVENT_MAPS.map((m) => [\`\${m.eventId}-\${m.channel.toUpperCase()}-\${m.provider.toUpperCase()}\`, m]),
);

/**
 * EvtxECmd keys maps on event id + channel + provider, all three exact
 * (case-insensitive). A record with no exact match gets no map.
 */
export function findMap(
  eventId: number,
  channel?: string | null,
  provider?: string | null,
): EventMap | undefined {
  if (!channel || !provider) return undefined;
  return BY_KEY.get(\`\${eventId}-\${channel.toUpperCase()}-\${provider.toUpperCase()}\`);
}
`,
);

const valueCount = maps.reduce(
  (n, m) => n + m.properties.reduce((k, p) => k + p.values.length, 0),
  0,
);
console.log(`${maps.length} maps, ${valueCount} value bindings`);
