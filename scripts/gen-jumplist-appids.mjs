// Generates src/parsers/jumplist/appids.ts from his JumpList library's
// Resources/AppIDs.txt (https://github.com/EricZimmerman/JumpList, MIT): the
// application a jump list's AppID belongs to.
//
//   node scripts/gen-jumplist-appids.mjs path/to/JumpList/JumpList/Resources/AppIDs.txt
//
// As his AppIdList loads it: "id"|"description", ids lower-cased, and a later
// line for the same id replaces the earlier one.
import { readFileSync, writeFileSync } from 'node:fs';

const src = process.argv[2];
if (!src) throw new Error('usage: node scripts/gen-jumplist-appids.mjs <AppIDs.txt>');

const strip = (s) => s.trim().replace(/^"+/, '').replace(/"+$/, '');
const table = {};
for (const line of readFileSync(src, 'utf8').split('\r\n')) {
  const segs = line.split('|');
  if (segs.length !== 2) continue;
  table[strip(segs[0]).toLowerCase()] = strip(segs[1]);
}

const out = `// Auto-generated by scripts/gen-jumplist-appids.mjs from his JumpList
// library's Resources/AppIDs.txt (https://github.com/EricZimmerman/JumpList).
// ${Object.keys(table).length} entries. Do not edit by hand.
export const APP_IDS: Record<string, string> = ${JSON.stringify(table, null, 0)};
`;
writeFileSync(new URL('../src/parsers/jumplist/appids.ts', import.meta.url), out);
console.log(`${Object.keys(table).length} app ids`);
