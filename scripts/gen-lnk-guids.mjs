/**
 * Regenerates src/parsers/lnk/guids.ts from Eric Zimmerman's GuidMapping table.
 *
 *   git clone --depth 1 https://github.com/EricZimmerman/GuidMapping.git
 *   node scripts/gen-lnk-guids.mjs path/to/GuidMapping/Resources/GuidToName.txt
 *
 * A shell item can name a folder by GUID instead of by path, and without this
 * table those items read as a bare GUID where LECmd shows "Desktop" or "My
 * Computer". The file is one "guid|name" pair per line.
 */
import { readFileSync, writeFileSync } from 'node:fs';

const src = process.argv[2];
if (!src) {
  console.error('usage: node scripts/gen-lnk-guids.mjs <GuidToName.txt>');
  process.exit(1);
}

const pairs = [];
for (const line of readFileSync(src, 'utf8').replace(/^﻿/, '').split(/\r?\n/)) {
  const at = line.indexOf('|');
  if (at <= 0) continue;
  const guid = line.slice(0, at).trim().toLowerCase().replace(/^\{|\}$/g, '');
  const name = line.slice(at + 1).trim();
  if (guid && name) pairs.push([guid, name]);
}

// Later duplicates win, matching a dictionary built by walking the file.
const table = new Map(pairs);

writeFileSync(
  new URL('../src/parsers/lnk/guids.ts', import.meta.url),
  `// Auto-generated by scripts/gen-lnk-guids.mjs from Eric Zimmerman's
// GuidMapping table (https://github.com/EricZimmerman/GuidMapping,
// Resources/GuidToName.txt). ${table.size} entries. Do not edit by hand.
//
// Imported dynamically so a session that never opens a shortcut never pays for
// it.
export const GUID_NAMES: Record<string, string> = ${JSON.stringify(
    Object.fromEntries(table),
  )};
`,
);

console.log(`${table.size} GUID names`);
