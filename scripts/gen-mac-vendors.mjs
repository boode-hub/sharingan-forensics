// Generates src/parsers/lnk/macs.ts from LECmd's Resources/MACs.txt
// (https://github.com/EricZimmerman/LECmd, MIT): the vendor LECmd prints in
// its MACVendor column for the MAC address in a shortcut's tracker block.
//
//   node scripts/gen-mac-vendors.mjs path/to/LECmd/LECmd/Resources/MACs.txt
//
// He upper-cases each line as he loads it and keeps the first entry for a
// prefix, so this does the same.
import { readFileSync, writeFileSync } from 'node:fs';

const src = process.argv[2];
if (!src) throw new Error('usage: node scripts/gen-mac-vendors.mjs <MACs.txt>');

const table = {};
for (const line of readFileSync(src, 'utf8').split(/\r?\n/)) {
  if (line.trim().length === 0) continue;
  const [key, value = ''] = line.toUpperCase().split('\t');
  if (!(key.trim() in table)) table[key.trim()] = value.trim();
}

const out = `// Auto-generated by scripts/gen-mac-vendors.mjs from LECmd's MACs.txt
// (https://github.com/EricZimmerman/LECmd, Resources/MACs.txt).
// ${Object.keys(table).length} entries. Do not edit by hand.
//
// Imported dynamically, and only for a shortcut that has a MAC address.
export const MAC_VENDORS: Record<string, string> = ${JSON.stringify(table)};
`;
writeFileSync(new URL('../src/parsers/lnk/macs.ts', import.meta.url), out);
console.log(`${Object.keys(table).length} prefixes`);
