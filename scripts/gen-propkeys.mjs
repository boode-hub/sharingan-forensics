// Generates src/core/propkeys.ts from the PropertyStoreInfo table in his
// ExtensionBlocks Utils.cs (https://github.com/EricZimmerman/ExtensionBlocks,
// MIT): the names of property keys, which he prints beside each value.
//
//   node scripts/gen-propkeys.mjs path/to/ExtensionBlocks/ExtensionBlocks/Utils.cs
import { readFileSync, writeFileSync } from 'node:fs';

const src = process.argv[2];
if (!src) throw new Error('usage: node scripts/gen-propkeys.mjs <Utils.cs>');

const text = readFileSync(src, 'utf8');
const start = text.indexOf('PropertyStoreInfo = new Dictionary');
const end = text.indexOf('};', start);
const body = text.slice(start, end);

const table = {};
const block = /\{\s*"([0-9a-f-]{36})"\s*,\s*new HashSet<IdName>\(\)\s*\{([\s\S]*?)\}\s*\}/gi;
for (const m of body.matchAll(block)) {
  const g = m[1].toLowerCase();
  table[g] ??= {};
  for (const e of m[2].matchAll(/new IdName\s*\(\s*(\d+)\s*,\s*"([^"]*)"\s*\)/g)) {
    table[g][e[1]] = e[2];
  }
}

const out = `// Auto-generated by scripts/gen-propkeys.mjs from the PropertyStoreInfo
// table in his ExtensionBlocks Utils.cs (https://github.com/EricZimmerman/ExtensionBlocks).
// ${Object.keys(table).length} property sets. Do not edit by hand.
export const PROPERTY_KEYS: Record<string, Record<string, string>> = ${JSON.stringify(table)};
`;
writeFileSync(new URL('../src/core/propkeys.ts', import.meta.url), out);
console.log(`${Object.keys(table).length} property sets, ${Object.values(table).reduce((n, t) => n + Object.keys(t).length, 0)} keys`);
